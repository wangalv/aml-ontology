/* The "Data alignment and mapping" box: the vocabulary of the source data, how each source term corresponds to an AML concept, and the mapping to tables and columns.
   Written here, not read from a data file. The terms and the Turtle come from the AML OBDA demo (ontology/alignment/source_vocabulary.ttl,
   ontology/alignment/aml_data_alignment.ttl, mappings/transaction/tx_features.r2rml.ttl, mappings/customer/customer.r2rml.ttl and
   mappings/lenses/tx_features.lens.json), a draft that no domain expert has reviewed. Uses AML_TERMS and ttlBlock from concepts.js. */

/* [term, kind, meaning and limits of the data, the AML concept it answers or null] */
const DATA_TERMS = [
  ['Transaction', 'Class', 'One transfer from one account to another.', 'FundsTransfer'],
  ['Account', 'Class', 'An account, identified by its id in the data.', 'Account'],
  ['txId', 'Property', 'Identifier of the transaction in the data.', 'transferId'],
  ['timestamp', 'Property', 'When the transfer happened. Minute resolution; the data covers 1 to 18 September 2022.', 'transferTime'],
  ['fromAccount', 'Property', 'The paying account.', 'originator'],
  ['toAccount', 'Property', 'The receiving account.', 'beneficiary'],
  ['sameBank', 'Property', 'True when both accounts are at the same bank; false means between banks. Between banks is not cross-border: the data has no country.', 'sameInstitution'],
  ['amountLog', 'Property', 'A logarithm of the amount (which log is not yet confirmed). The raw amount is not in the data.', null],
  ['customerType', 'Property', 'Individual or Company. Synthetic: generated by this project, not part of the IBM data.', null],
  ['industry', 'Property', 'Industry of a Company account; absent for individuals. Synthetic, assigned at random independent of the transactions.', null],
  ['onboardingTenureDays', 'Property', 'Days since the account was opened, 30 to 3650. Synthetic: a random draw with no reference date, so it must not be compared with transaction times.', null],
  ['pepFlag', 'Property', 'Politically exposed person flag. Synthetic.', null],
  ['riskRating', 'Property', 'Low, Medium or High. Synthetic: derived from the declared attributes, not from transactions.', null],
];

/* [data term, table, column, how the value is built] The tables are views over the real tables: see LENSES. */
const COLUMN_MAP = [
  ['txId', 'tx', 'tx_id', 'a whole number'],
  ['timestamp', 'tx', 'ts', 'a date and time'],
  ['fromAccount', 'tx', 'from_account', 'an account IRI built from the account id'],
  ['toAccount', 'tx', 'to_account', 'an account IRI built from the account id'],
  ['amountLog', 'tx', 'amount_log', 'a decimal number'],
  ['sameBank', 'tx', 'is_same_bank', 'true or false'],
  ['customerType', 'kyc', 'customer_type', 'text'],
  ['industry', 'kyc', 'industry_or_null', 'text; an empty industry becomes NULL, so individuals get no industry'],
  ['onboardingTenureDays', 'kyc', 'onboarding_tenure_days', 'a whole number'],
  ['pepFlag', 'kyc', 'pep_flag', 'true or false'],
  ['riskRating', 'kyc', 'risk_rating', 'text'],
];

const LENSES = { relations: [
  { name: ['tx'], baseRelation: ['tx_features'], type: 'BasicLens', uniqueConstraints: { added: [{ name: 'tx_pk', determinants: ['tx_id'] }] } },
  { name: ['kyc'], baseRelation: ['kyc_profiles'], type: 'BasicLens', columns: { added: [{ name: 'industry_or_null', expression: "NULLIF(industry, '')" }], hidden: ['industry'] },
    uniqueConstraints: { added: [{ name: 'kyc_pk', determinants: ['account_id'] }] } },
] };

const TTL_ALIGNMENT = `@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix fcd:  <https://example.org/fincrime-data#> .
@prefix amd:  <https://example.org/aml-data#> .

# "This data term is a kind of that AML concept"
fcd:Transaction  rdfs:subClassOf    amd:FundsTransfer .
fcd:Account      rdfs:subClassOf    amd:Account .
fcd:txId         rdfs:subPropertyOf amd:transferId .
fcd:timestamp    rdfs:subPropertyOf amd:transferTime .
fcd:fromAccount  rdfs:subPropertyOf amd:originator .
fcd:toAccount    rdfs:subPropertyOf amd:beneficiary .
fcd:sameBank     rdfs:subPropertyOf amd:sameInstitution .

# amd:Jurisdiction has no line here. Nothing in the data answers it,
# so an indicator that needs it is reported as "cannot check".`;

const TTL_VOCABULARY = `@prefix owl:  <http://www.w3.org/2002/07/owl#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix xsd:  <http://www.w3.org/2001/XMLSchema#> .
@prefix fcd:  <https://example.org/fincrime-data#> .

fcd:fromAccount a owl:ObjectProperty ;
    rdfs:domain fcd:Transaction ; rdfs:range fcd:Account ;
    rdfs:comment "The paying account." .

# The comment records a limit of the data, so it travels with the term
fcd:sameBank a owl:DatatypeProperty ;
    rdfs:domain fcd:Transaction ; rdfs:range xsd:boolean ;
    rdfs:comment "True when the paying and the receiving account are at the same bank. False means between banks. Between banks is not the same as cross-border: the data has no country." .`;

const TTL_R2RML = `@prefix rr:  <http://www.w3.org/ns/r2rml#> .
@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .
@prefix fcd: <https://example.org/fincrime-data#> .
@prefix map: <https://example.org/obda/tx_features#> .

# Every row of table tx becomes one fcd:Transaction; each column becomes a property of it
map:TransactionMap a rr:TriplesMap ;
    rr:logicalTable [ rr:tableName "tx" ] ;
    rr:subjectMap [ rr:template "https://example.org/transaction/{tx_id}" ; rr:class fcd:Transaction ] ;
    rr:predicateObjectMap
        [ rr:predicate fcd:txId ;        rr:objectMap [ rr:column "tx_id" ; rr:datatype xsd:integer ] ] ,
        [ rr:predicate fcd:fromAccount ; rr:objectMap [ rr:template "https://example.org/account/{from_account}" ; rr:termType rr:IRI ] ] ,
        [ rr:predicate fcd:sameBank ;    rr:objectMap [ rr:column "is_same_bank" ; rr:datatype xsd:boolean ] ] .`;

const ALIGN_SECTIONS = ['Source vocabulary and alignment', 'Mapping to tables and columns'];
const ALIGN = { section: ALIGN_SECTIONS[0] };

function alignmentSection() {
  const aligned = DATA_TERMS.filter((t) => t[3]), context = DATA_TERMS.filter((t) => !t[3]);
  const unanswered = AML_TERMS.filter((t) => !t[3]).map((t) => t[0]);
  return h('div', {},
    h('p', {}, 'The source vocabulary is the set of terms for our two tables, written the way the data has them. It records the limits of the data as well: no raw amount, no country, a tenure with no reference date. ' +
      `Each term that answers an AML concept is linked to it by one line, "is a kind of". ${aligned.length} of the ${DATA_TERMS.length} data terms are linked.`),
    dataTable(['Data term', 'Kind', 'Meaning, and what to know about the data', 'Answers this AML concept'],
      DATA_TERMS.map(([term, kind, meaning, concept]) => ({ key: term, cells: [h('code', {}, 'fcd:' + term), kind, meaning,
        concept ? h('code', {}, 'amd:' + concept) : badge('gray', 'None: kept as a data term')] })),
      { maxHeight: 460 }),
    h('p', { style: { marginTop: '10px' } }, `The ${context.length} terms with no AML concept are the account background and the log amount: they are shown to the investigator, but no indicator needs them as evidence. ` +
      `In the other direction, ${unanswered.length} AML concepts have no data term under them: `, unanswered.join(', '), '. ' +
      'That is how "cannot check" is decided: an AML concept with no line in the alignment cannot be answered from this data.'),
    ttlBlock('Example in Turtle: the alignment, all seven lines', TTL_ALIGNMENT),
    ttlBlock('Example in Turtle: two terms of the source vocabulary (excerpt)', TTL_VOCABULARY));
}

function mappingSection() {
  return h('div', {},
    h('p', {}, 'The mapping says which column of which table holds each data term. It is the only place that knows the physical tables, so a change of database changes this and nothing above it. ' +
      'In the AML OBDA demo it is an R2RML mapping, and an OBDA engine (Ontop) reads it together with the alignment to rewrite a question asked in AML concepts into SQL.'),
    h('p', {}, 'For example, a question about ', h('code', {}, 'amd:originator'), ' becomes ', h('code', {}, 'fcd:fromAccount'), ' through the alignment, then column ',
      h('code', {}, 'from_account'), ' of table ', h('code', {}, 'tx'), ' through the mapping, and then a SQL query on the database.'),
    dataTable(['Data term', 'Table', 'Column', 'The value is'],
      COLUMN_MAP.map(([term, table, col, how]) => ({ key: term, cells: [h('code', {}, 'fcd:' + term), h('code', {}, table), h('code', {}, col), how] })),
      { maxHeight: 460 }),
    ttlBlock('Example in Turtle: the R2RML mapping of the transfers (excerpt)', TTL_R2RML),
    ttlBlock('SQL views: the two tables the mapping reads are views over the real tables (JSON)', JSON.stringify(LENSES, null, 2)),
    caption('tx is the table tx_features with tx_id declared unique, so a query over several properties does not join the table to itself once per property. kyc is kyc_profiles with an empty industry turned into NULL.'));
}

function renderAlignment(root) {
  const pillBox = h('div'), body = h('div');
  root.append(
    h('p', {}, 'Two things sit in this box, and together they connect the AML concepts to the data. ',
      h('strong', {}, 'Alignment'), ' says which AML concept each source term answers. ',
      h('strong', {}, 'Mapping'), ' says which table and column holds it.'),
    caption('A draft written for the demo and not reviewed by a domain expert. It is built for the synthetic IBM AML data of this demo; the account background (customer type, industry, tenure, PEP flag, risk rating) is synthetic too, generated by this project. ' +
      'The namespace is a placeholder.'),
    pillBox, body);
  function show() {
    pillBox.replaceChildren(pills(ALIGN_SECTIONS.map((s) => [s, s]), ALIGN.section, (s) => { ALIGN.section = s; show(); }));
    body.replaceChildren(ALIGN.section === ALIGN_SECTIONS[0] ? alignmentSection() : mappingSection());
  }
  show();
}
